// Local Postgres integration: node tools/classroom/test-photo-migration.mjs <pglite/dist/index.js>
import fs from 'node:fs';
import assert from 'node:assert/strict';
import path from 'node:path';
import { pathToFileURL } from 'node:url';
const { PGlite } = await import(pathToFileURL(path.resolve(process.argv[2])));
const db = new PGlite();
const id=n=>`00000000-0000-0000-0000-${String(n).padStart(12,'0')}`;
await db.exec(`
create role anon; create role authenticated;
create schema auth; create schema storage;
create function auth.uid() returns uuid language sql as $$select nullif(current_setting('app.uid',true),'')::uuid$$;
create function public.my_profile_id() returns uuid language sql as $$select auth.uid()$$;
create function public.has_perm(p text) returns boolean language sql as $$select coalesce(current_setting('app.admin',true)='yes',false)$$;
create table public.profiles(id uuid primary key);
create table public.classes(id uuid primary key, teacher_id uuid);
create table public.class_teachers(class_id uuid,teacher_id uuid);
create table public.sessions(class_id uuid,teacher_id uuid);
create table public.class_students(class_id uuid,student_id uuid);
create table storage.buckets(id text primary key,name text,public boolean,file_size_limit bigint,allowed_mime_types text[]);
create table storage.objects(bucket_id text,name text);
alter table storage.objects enable row level security;
insert into profiles values('${id(10)}'),('${id(11)}');
insert into classes values('${id(1)}','${id(2)}'),('${id(3)}','${id(4)}');
insert into class_teachers values('${id(1)}','${id(5)}');
insert into sessions values('${id(1)}','${id(6)}');
insert into class_students values('${id(1)}','${id(10)}'),('${id(3)}','${id(11)}');
insert into storage.objects values('class-photos','${id(1)}/group/a.jpg'),('class-photos','${id(1)}/${id(10)}/a.jpg'),('class-photos','${id(3)}/group/b.jpg');
`);
await db.exec(fs.readFileSync('supabase/migrations/0054_class_photos.sql','utf8'));
await db.exec(`grant usage on schema public,storage,auth to authenticated,anon; grant select on public.class_photos to authenticated; grant all on storage.objects to authenticated; set role authenticated;`);
const setUser=uid=>db.query("select set_config('app.uid',$1,false)",[uid]);
const save=changes=>db.query('select save_class_photos($1,$2)',[id(1),JSON.stringify(changes)]);
const rows=async()=> (await db.query('select * from class_photos order by photo_key')).rows;
await setUser(id(2));
await save({group:`${id(1)}/group/a.jpg`,[id(10)]:`${id(1)}/${id(10)}/a.jpg`});
assert.equal((await rows()).length,2);
await assert.rejects(()=>save({group:null,[id(11)]:`${id(1)}/group/a.jpg`}),/không thuộc lớp/);
assert.equal((await rows()).length,2,'Invalid member rolls back the earlier group deletion');
await assert.rejects(()=>save({group:`${id(3)}/group/b.jpg`}),/không thuộc lớp/);
await assert.rejects(()=>save({group:`${id(1)}/missing.jpg`}),/chưa được tải lên/);
await setUser(id(4));assert.equal((await rows()).length,0,'Other-class teacher cannot read portraits');
await assert.rejects(()=>save({group:null}),/Không có quyền/);
await assert.rejects(()=>db.exec(`insert into storage.objects values('class-photos','${id(1)}/forged.jpg')`),/row-level security/);
for(const uid of [id(5),id(6)]) {await setUser(uid);await save({group:`${id(1)}/group/a.jpg`});assert.equal((await rows()).length,2,'Assistant and assigned-session teacher can manage photos');}
await setUser(id(10));assert.equal((await rows()).length,0,'Student cannot read class photo collection');
await assert.rejects(()=>save({group:null}),/Không có quyền/);
await setUser(id(7));await db.exec("select set_config('app.admin','yes',false)");await save({[id(10)]:null});assert.equal((await rows()).length,1);
assert.equal((await db.query("select can_access_class_photo_path('malformed/path') as ok")).rows[0].ok,false);
await db.exec('set role anon');await assert.rejects(()=>save({group:null}),/permission denied/);
await db.close();console.log('PASS: photo migration, atomic saves, class membership, storage path ownership, private reads, teacher/assistant/session-teacher/admin access, student/anonymous rejection.');
